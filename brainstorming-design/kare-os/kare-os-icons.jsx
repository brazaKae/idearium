function PixelGrid({ grid, fill = '#0A0A0A', scale = 3 }) {
  const cells = [];
  for (let y = 0; y < grid.length; y++) {
    for (let x = 0; x < grid[y].length; x++) {
      if (grid[y][x] === 1) {
        cells.push(<rect key={`${x}-${y}`} x={x*scale} y={y*scale} width={scale} height={scale} fill={fill} />);
      }
    }
  }
  return <g>{cells}</g>;
}

function Icon({ name, scale = 3, color = '#0A0A0A', size }) {
  if (!ICONS[name]) return null;
  const w = ICONS[name][0].length * scale;
  const h = ICONS[name].length * scale;
  return (
    <svg width={size || w} height={size || h} viewBox={`0 0 ${w} ${h}`} className="pixel">
      <PixelGrid grid={ICONS[name]} fill={color} scale={scale} />
    </svg>
  );
}

